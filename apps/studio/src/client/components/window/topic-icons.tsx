const BY_NAME = new Map(TOPIC_ICONS.map((entry) => [entry.name, entry.Icon]));

/** The icon a topic's file names, when it names one this build still has. */
function topicIconOf(name: string | undefined): Icon | undefined {
  return name ? BY_NAME.get(name) : undefined;
}

/** The icons a search reads to, by their names and the words a person would guess. */
export function searchTopicIcons(query: string): TopicIcon[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) {
    return TOPIC_ICONS;
  }
  return TOPIC_ICONS.filter((entry) => {
    const text =
      `${entry.name.replaceAll(/([a-z])([A-Z])/g, "$1 $2")} ${entry.words}`.toLowerCase();
    return words.every((word) => text.includes(word));
  });
}

/**
 * A topic's face with nothing under it: its icon, filled, in the topic's ink;
 * failing that its emoji; failing that the first letter of its name, so a
 * topic nobody marked is still told apart from its neighbors. Wear it inside
 * something that carries the topic's tint for the ink to be the topic's.
 */
export function TopicGlyph({
  className,
  topic,
}: {
  /** Sizes the icon and the letter; an emoji takes the text size. */
  className?: string;
  topic: { emoji?: string; icon?: string; name?: string };
}) {
  const TopicIcon = topicIconOf(topic.icon);
  if (TopicIcon) {
    return (
      <TopicIcon
        className={cn("shrink-0 text-(--topic-tint-ink)", className)}
        weight="fill"
      />
    );
  }
  if (topic.emoji) {
    return <span className="leading-none">{topic.emoji}</span>;
  }
  // By grapheme, so a name that starts with an emoji or an accented letter
  // gives one character rather than half of one.
  const [first] = new Intl.Segmenter().segment(topic.name ?? "?");
  return (
    <span
      className="leading-none font-semibold uppercase"
      // The tint's ink rather than the color itself: a pale pick's own hex
      // would vanish on its own tile.
      style={{ color: "var(--topic-tint-ink, currentColor)" }}
    >
      {first?.segment ?? "?"}
    </span>
  );
}
