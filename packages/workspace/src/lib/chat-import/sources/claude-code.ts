import fs from "node:fs/promises";
import path from "node:path";
import { parallel } from "radashi";

import type { ChatSource, ImportCandidate, ImportedTranscript } from "../model";
import {
  type AssistantPart,
  ConversationFolder,
  dateOf,
  FileCache,
  FILES_AT_ONCE,
  homeRelative,
  isRecord,
  lastTimestamp,
  parseRecord,
  previewFrom,
  readLines,
  stringOf,
  titleFrom,
  type UserPart,
} from "./shared";

/**
 * Claude Code's sessions: one JSONL log per session under
 * `~/.claude/projects/<folder>/`, the folder named for the working directory
 * with every `/` written as `-`. A subagent's run is its own log, under
 * `<session>/subagents/` (older builds put `agent-*.jsonl` beside the
 * sessions), its records marked `isSidechain`.
 *
 * A log mixes the conversation with bookkeeping (titles, modes, hooks, file
 * snapshots, request copies), so a listing reads each line's first bytes and
 * parses only the records that can say something. A user record carrying
 * only tool results is the harness answering the model, not the person.
 */

const KIND = "claude-code";

/** A line this long or longer is read by its first bytes when listing. */
const LONG_LINE = 8192;
const HEAD_BYTES = 512;

/** Records that open with `"type"` and still matter. */
const TITLE_TYPES = new Set(["custom-title", "ai-title", "summary"]);

/** Text the harness writes into a user record for the model, not from the person. */
const NOISE_PREFIXES = [
  "<command-name>",
  "<command-message>",
  "<command-args>",
  "<local-command-stdout>",
  "<local-command-stderr>",
  "<local-command-caveat>",
  "<bash-input>",
  "<bash-stdout>",
  "<bash-stderr>",
  "<task-notification>",
  "<system-reminder>",
  "<user-prompt-submit-hook>",
  "[Request interrupted by user",
  "Caveat: The messages below were generated by the user while running local commands",
];

interface Scanned {
  candidate: ImportCandidate;
  messages: ImportedTranscript["messages"];
}

export function claudeCodeSource({ homeDir }: { homeDir: string }): ChatSource {
  const root = path.join(homeDir, ".claude", "projects");
  const cache = new FileCache<ImportCandidate | null>();
  let index = new Map<string, string>();

  async function list(): Promise<ImportCandidate[]> {
    const files = await sessionFiles(root);
    cache.retain(new Set(files));
    const listed = await parallel(
      { limit: FILES_AT_ONCE },
      files,
      async (file) => {
        const candidate = await cache.get(file, async () =>
          scanFile(file, { homeDir, keepText: false })
            .then((scanned) => scanned?.candidate ?? null)
            .catch(() => null),
        );
        return candidate ? { candidate, file } : undefined;
      },
    );
    const chosen = new Map<
      string,
      { candidate: ImportCandidate; file: string }
    >();
    for (const entry of listed) {
      if (!entry) {
        continue;
      }
      const held = chosen.get(entry.candidate.sourceId);
      if (!held || isFuller(entry.candidate, held.candidate)) {
        chosen.set(entry.candidate.sourceId, entry);
      }
    }
    index = new Map([...chosen].map(([id, entry]) => [id, entry.file]));
    return [...chosen.values()]
      .map((entry) => entry.candidate)
      .toSorted((a, b) => b.updatedAt.getTime() - a.updatedAt.getTime());
  }

  return {
    kind: KIND,
    list,
    async *read(sourceIds) {
      if (sourceIds.some((id) => !index.has(id))) {
        await list();
      }
      for (const id of sourceIds) {
        const file = index.get(id);
        const scanned = file
          ? await scanFile(file, { homeDir, keepText: true }).catch(
              () => undefined,
            )
          : undefined;
        if (scanned) {
          yield { ...scanned.candidate, messages: scanned.messages };
        }
      }
    },
  };
}

/** Of two logs naming one session (a session moved between folders), the fuller one. */
function isFuller(a: ImportCandidate, b: ImportCandidate): boolean {
  return a.messages !== b.messages
    ? a.messages > b.messages
    : a.updatedAt.getTime() > b.updatedAt.getTime();
}

/** Every session and subagent log under the projects folder. */
async function sessionFiles(root: string): Promise<string[]> {
  const entries = await fs.readdir(root, { recursive: true }).catch(() => []);
  return entries
    .filter((entry) => entry.endsWith(".jsonl") && isSessionPath(entry))
    .map((entry) => path.join(root, entry))
    .toSorted();
}

/** `<folder>/<id>.jsonl`, or a subagent's `agent-*.jsonl` deeper in a session's folder. */
function isSessionPath(relative: string): boolean {
  const segments = relative.split(path.sep);
  return (
    segments.length === 2 ||
    (segments.length > 2 && segments.at(-1)?.startsWith("agent-") === true)
  );
}

function isSubagentFile(file: string): boolean {
  return path.basename(file).startsWith("agent-");
}

/** Reads one log: everything a listing shows, and the messages when `keepText`. */
export async function scanFile(
  file: string,
  { homeDir, keepText }: { homeDir: string; keepText: boolean },
): Promise<Scanned | undefined> {
  const folder = new ConversationFolder({ keepText });
  const titles: { [type: string]: string } = {};
  let cwd: string | undefined;
  let sidechain: boolean | undefined;

  for await (const line of readLines(file)) {
    if (line.length >= LONG_LINE && !keepText) {
      const head = line.toString("latin1", 0, HEAD_BYTES);
      const skimmed = skimLongLine(head, line);
      if (skimmed) {
        sidechain ??= skimmed.sidechain;
        if (skimmed.sidechain === sidechain) {
          if (skimmed.assistant) {
            folder.assistant(skimmed.assistant);
          } else {
            folder.activity(skimmed.at);
          }
        }
        continue;
      }
    }
    const type = leadingType(line);
    if (
      type !== undefined &&
      !TITLE_TYPES.has(type) &&
      type !== "user" &&
      type !== "assistant"
    ) {
      continue;
    }
    const record = parseRecord(line);
    if (!record) {
      continue;
    }
    const recordType = stringOf(record.type);
    if (
      recordType === "custom-title" ||
      recordType === "ai-title" ||
      recordType === "summary"
    ) {
      const title = stringOf(
        record.customTitle ?? record.aiTitle ?? record.summary,
      )?.trim();
      if (title) {
        titles[recordType] = title;
      }
      continue;
    }
    if (
      recordType !== "user" &&
      recordType !== "assistant" &&
      recordType !== "attachment"
    ) {
      continue;
    }
    const at = dateOf(record.timestamp);
    if (!at) {
      continue;
    }
    const isSidechain = record.isSidechain === true;
    sidechain ??= isSidechain;
    if (isSidechain !== sidechain) {
      continue;
    }
    cwd ??= stringOf(record.cwd);
    if (recordType === "user") {
      const part = userPart(record, at);
      if (part) {
        folder.user(part);
      } else {
        folder.activity(at);
      }
    } else if (recordType === "assistant") {
      const part = assistantPart(record, at);
      if (part) {
        folder.assistant(part);
      }
    } else {
      const part = queuedPrompt(record, at);
      if (part) {
        folder.user(part);
      }
    }
  }

  const folded = folder.finish();
  if (!folded.createdAt || !folded.updatedAt || folded.count === 0) {
    return undefined;
  }
  const sourceId = path.basename(file, ".jsonl");
  const prompt = folded.firstPrompt;
  const title =
    titles["custom-title"] ??
    titles["ai-title"] ??
    titles.summary ??
    (prompt ? titleFrom(prompt) : "");
  const incidental =
    isSubagentFile(file) ||
    sidechain === true ||
    !folded.prompted ||
    !folded.replied;
  return {
    candidate: {
      createdAt: folded.createdAt,
      kind: KIND,
      messages: folded.count,
      sourceId,
      title,
      updatedAt: folded.updatedAt,
      ...(prompt ? { preview: previewFrom(prompt) } : {}),
      ...(cwd ? { project: homeRelative(cwd, homeDir) } : {}),
      ...(incidental ? { incidental: true } : {}),
    },
    messages: folded.messages,
  };
}

/** The record type of a line that opens with it (`{"type":"mode",…`), read without parsing. */
function leadingType(line: Buffer): string | undefined {
  const opening = '{"type":"';
  if (
    line.length < opening.length ||
    line.toString("latin1", 0, opening.length) !== opening
  ) {
    return undefined;
  }
  const end = line.indexOf('"', opening.length);
  return end === -1 ? undefined : line.toString("latin1", opening.length, end);
}

/**
 * A long line read by its first bytes when only counting: a tool's result
 * (the bulk of a log) or one block of a reply, with its time read from the
 * line's end. Anything else is left for a full parse.
 */
function skimLongLine(
  head: string,
  line: Buffer,
): { assistant?: AssistantPart; at: Date; sidechain: boolean } | undefined {
  const sidechain = head.includes('"isSidechain":true');
  if (
    head.includes('"type":"user"') &&
    head.includes('"content":[{"tool_use_id":"')
  ) {
    const at = lastTimestamp(line);
    return at ? { at, sidechain } : undefined;
  }
  if (
    head.includes('"attachment":{"type":"') &&
    !head.includes('"queued_command"')
  ) {
    const at = lastTimestamp(line);
    return at ? { at, sidechain } : undefined;
  }
  if (
    head.includes('"type":"assistant"') &&
    !head.includes('"model":"<synthetic>"')
  ) {
    const at = lastTimestamp(line);
    const thinking = head.includes('"content":[{"type":"thinking"');
    return at
      ? { assistant: thinking ? undefined : { at, text: true }, at, sidechain }
      : undefined;
  }
  return undefined;
}

function userPart(
  record: Record<string, unknown>,
  at: Date,
): UserPart | undefined {
  if (
    record.isMeta === true ||
    record.isCompactSummary === true ||
    record.isVisibleInTranscriptOnly === true
  ) {
    return undefined;
  }
  if (isRecord(record.origin) && record.origin.kind !== "human") {
    return undefined;
  }
  const message = isRecord(record.message) ? record.message : undefined;
  return message ? personPart(message.content, at) : undefined;
}

/** What the person said in a user record's content, or undefined when it was not them. */
function personPart(content: unknown, at: Date): UserPart | undefined {
  if (typeof content === "string") {
    return { at, text: personText(content) };
  }
  if (!Array.isArray(content)) {
    return undefined;
  }
  const texts: string[] = [];
  let attachments = 0;
  for (const block of content) {
    if (!isRecord(block)) {
      continue;
    }
    if (block.type === "tool_result") {
      return undefined;
    }
    if (block.type === "text") {
      const text = personText(stringOf(block.text) ?? "");
      if (text !== "") {
        texts.push(text);
      }
    } else if (block.type === "image" || block.type === "document") {
      attachments += 1;
    }
  }
  return {
    at,
    text: texts.join("\n\n"),
    ...(attachments > 0 ? { attachments } : {}),
  };
}

function personText(text: string): string {
  const stripped = text
    .replaceAll(/<system-reminder>[\s\S]*?<\/system-reminder>/g, "")
    .trim();
  return NOISE_PREFIXES.some((prefix) => stripped.startsWith(prefix))
    ? ""
    : stripped;
}

function assistantPart(
  record: Record<string, unknown>,
  at: Date,
): AssistantPart | undefined {
  const message = isRecord(record.message) ? record.message : undefined;
  const model = stringOf(message?.model);
  if (!message || model === "<synthetic>") {
    return undefined;
  }
  const texts: string[] = [];
  const tools: string[] = [];
  if (typeof message.content === "string") {
    texts.push(message.content);
  } else if (Array.isArray(message.content)) {
    for (const block of message.content) {
      if (!isRecord(block)) {
        continue;
      }
      if (block.type === "text") {
        texts.push(stringOf(block.text) ?? "");
      } else if (
        block.type === "tool_use" ||
        block.type === "server_tool_use"
      ) {
        tools.push(stringOf(block.name) ?? "tool");
      }
    }
  }
  return { at, text: texts.join("\n\n"), tools, ...(model ? { model } : {}) };
}

/** A prompt the person typed while a reply was still running, which joins the session later. */
function queuedPrompt(
  record: Record<string, unknown>,
  at: Date,
): UserPart | undefined {
  const attachment = isRecord(record.attachment)
    ? record.attachment
    : undefined;
  if (
    attachment?.type !== "queued_command" ||
    attachment.commandMode !== "prompt" ||
    attachment.isMeta === true ||
    (isRecord(attachment.origin) && attachment.origin.kind !== "human")
  ) {
    return undefined;
  }
  return personPart(attachment.prompt, dateOf(attachment.timestamp) ?? at);
}
