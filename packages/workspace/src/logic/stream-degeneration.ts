import { deflateRawSync } from "node:zlib";

/** How much of the latest text each check compresses. */
const WINDOW_CHARS = 8192;
/** How much new text arrives between checks. */
const CHECK_EVERY_CHARS = 4096;
/**
 * The compressed share of a window at or under which it counts as repetition.
 * A model stuck in a loop measured 0.8% to 1.0% on every window of its
 * captured streams, and the most repetitive honest text across 289 eval
 * sessions (python-pptx code for a deck) 13.4%.
 */
const DEGENERATE_RATIO = 0.05;
/** Checks in a row that must find repetition, so one dense stretch never trips it. */
const HITS_TO_TRIP = 2;
/**
 * How many characters of a line are read before deciding whether it opens or
 * closes a fence: a line of nothing but indentation is decided by then.
 */
const FENCE_HEAD_MAX_CHARS = 64;
const FENCE_MARKER = /^(```|~~~)/;

/**
 * Whether a model's streamed text has fallen into a loop: the same few
 * sentences over and over, inside one reply, until something outside stops
 * it. Text a model means to write compresses to a fifth or more of its size;
 * a loop compresses to almost nothing, and `deflate` measures that without
 * knowing what repeats or how often.
 *
 * Fenced code blocks are left out. Data and code written out on purpose (a
 * JSON array of like records, rows of CSV, a slide-building script) can
 * compress to within a few points of a loop, and a loop inside a fence still
 * ends at the output limit.
 *
 * Fed one stream's deltas in order, one instance per stream. Pure: it never
 * aborts anything itself.
 */
export class StreamDegeneration {
  private window = "";
  private sinceCheck = 0;
  private hits = 0;
  private tripped = false;
  private inFence = false;
  /** The current line's start while it may still be a fence marker. */
  private lineHead = "";
  /** Whether the current line is a fence marker; undefined until known. */
  private lineIsFence: boolean | undefined;

  /** Adds a delta and answers whether the stream has degenerated by now. */
  push(delta: string): boolean {
    if (this.tripped) {
      return true;
    }
    let kept = "";
    let start = 0;
    while (start < delta.length) {
      const newline = delta.indexOf("\n", start);
      const end = newline === -1 ? delta.length : newline + 1;
      kept += this.keptOfLine(delta.slice(start, end), newline !== -1);
      start = end;
    }
    // A check every `CHECK_EVERY_CHARS` however the text arrives, so a
    // provider sending it in large pieces is checked as often as one sending
    // a word at a time.
    while (kept.length > 0 && !this.tripped) {
      const piece = kept.slice(0, CHECK_EVERY_CHARS - this.sinceCheck);
      kept = kept.slice(piece.length);
      this.window = (this.window + piece).slice(-WINDOW_CHARS);
      this.sinceCheck += piece.length;
      if (this.sinceCheck < CHECK_EVERY_CHARS) {
        break;
      }
      this.sinceCheck = 0;
      if (this.window.length < WINDOW_CHARS) {
        continue;
      }
      this.hits =
        compressedRatio(this.window) <= DEGENERATE_RATIO ? this.hits + 1 : 0;
      this.tripped = this.hits >= HITS_TO_TRIP;
    }
    return this.tripped;
  }

  /**
   * What of a piece of the current line goes into the window: nothing inside
   * a fence or of a fence's own marker line, and the rest as it is. A line's
   * opening characters are held until they say which it is.
   */
  private keptOfLine(segment: string, endsLine: boolean): string {
    let kept: string;
    if (this.lineIsFence === undefined) {
      this.lineHead += segment;
      const head = this.lineHead.trimStart();
      if (
        head.length >= 3 ||
        endsLine ||
        this.lineHead.length >= FENCE_HEAD_MAX_CHARS
      ) {
        this.lineIsFence = FENCE_MARKER.test(head);
        if (this.lineIsFence) {
          this.inFence = !this.inFence;
        }
        kept = this.lineIsFence || this.inFence ? "" : this.lineHead;
        this.lineHead = "";
      } else {
        kept = "";
      }
    } else {
      kept = this.lineIsFence || this.inFence ? "" : segment;
    }
    if (endsLine) {
      this.lineHead = "";
      this.lineIsFence = undefined;
    }
    return kept;
  }
}

/** What share of its UTF-8 size `text` deflates to. */
export function compressedRatio(text: string): number {
  const bytes = Buffer.from(text, "utf8");
  return bytes.length === 0 ? 1 : deflateRawSync(bytes).length / bytes.length;
}
