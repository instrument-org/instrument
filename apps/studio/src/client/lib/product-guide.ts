import {
  SETTINGS_INDEX,
  SETTINGS_PAGES,
  type SettingsEntry,
} from "@/client/components/settings/settings-index";
import { formatAcceleratorFor } from "@/shared/format-accelerator";
import { SCREENS } from "@/shared/instrument-screens";
import {
  SHORTCUT_GUIDE_ENTRIES,
  SHORTCUT_GUIDE_GROUPS,
} from "@/shared/shortcut-guide";
import { APP_NAME, APP_NAME_SLUG } from "@instrument-org/shared";
import { type MenuItemConstructorOptions } from "electron";

/**
 * The part of the product guide skill that is read off the app rather than
 * written: every page and row of Settings, every screen a link can open,
 * every item of the menu bar, and every keyboard shortcut, each with the
 * address that links to it. A test keeps the skill's `reference.md` equal to
 * this, so a setting or menu item added to the app is one the agent can find
 * the day it ships. `menus` is the app window's menu bar as a Mac builds it,
 * which the test builds, since only the main process can.
 */
export function productGuideReference({
  menus,
}: {
  menus: MenuItemConstructorOptions[];
}): string {
  return [
    "<!-- Generated by apps/studio/src/client/lib/product-guide.test.ts from the app's settings index, screens and shortcut tables. Do not edit by hand: run `pnpm fix`. -->",
    "",
    `# ${APP_NAME} reference`,
    "",
    settingsSection(),
    screensSection(),
    menuBarSection(menus),
    shortcutsSection(),
  ].join("\n");
}

function settingsSection() {
  const lines = [
    "## Settings",
    "",
    // oxlint-disable-next-line studio/no-os-words -- tells the agent each system's key
    `Link a page or a row as \`[Label](${APP_NAME_SLUG}://settings/<name>)\`, with the name in backticks below. Settings opens at it, and a row is scrolled to and lit. Settings opens with ⌘, on a Mac (Ctrl+, elsewhere).`,
    "",
  ];
  for (const [tab, page] of Object.entries(SETTINGS_PAGES)) {
    if (page.developerOnly) {
      continue;
    }
    lines.push(`### ${tab} (\`${tab.toLowerCase()}\`)`, "", page.detail);
    if (page.shownWhen) {
      lines.push(
        "",
        `The sidebar lists this page only when ${page.shownWhen}, though a link opens it either way.`,
      );
    }
    lines.push("");
    const rows = SETTINGS_INDEX.filter(
      (entry): entry is Extract<typeof entry, { detail: string }> =>
        entry.tab === tab && "detail" in entry && !isDeveloperOnly(entry),
    );
    for (const row of rows) {
      const labels = SETTINGS_INDEX.filter(
        (entry) => "mark" in entry && entry.mark === row.id,
      ).map((entry) => `${entry.title} (\`${entry.id}\`)`);
      lines.push(
        `- **${row.title}** (\`${row.id}\`): ${sentence(row.detail)}${
          labels.length > 0 ? ` On it: ${labels.join(", ")}.` : ""
        }`,
      );
    }
    if (rows.length > 0) {
      lines.push("");
    }
  }
  return lines.join("\n");
}

function screensSection() {
  return [
    "## Screens",
    "",
    `Link one as \`[Label](${APP_NAME_SLUG}://screen/<name>)\`.`,
    "",
    ...Object.entries(SCREENS).map(
      ([name, screen]) =>
        `- **${screen.title}** (\`${name}\`): ${screen.detail}`,
    ),
    "",
  ].join("\n");
}

/**
 * Each menu of the bar and the items in it, by the labels the person sees.
 * An item with only a role (Undo, Minimize) is the system's own and goes
 * unlisted, as does a hidden one, so the list is what the app adds.
 */
function menuBarSection(menus: MenuItemConstructorOptions[]) {
  const lines = [
    "## Menu bar",
    "",
    // oxlint-disable-next-line studio/no-os-words -- tells the agent where each system shows the menus
    `On a Mac these are the menu bar's menus, the first named for ${APP_NAME}; on Windows and Linux the same menus open from the Menu button in the window's bar, with Settings and Quit at the end of File and updates and About at the end of Help.`,
    "",
  ];
  for (const menu of menus) {
    const items = (Array.isArray(menu.submenu) ? menu.submenu : []).flatMap(
      (item) =>
        item.type === "separator" || item.visible === false || !item.label
          ? []
          : [item.label],
    );
    if (items.length > 0) {
      lines.push(`- **${menu.label ?? APP_NAME}**: ${items.join(", ")}`);
    }
  }
  lines.push("");
  return lines.join("\n");
}

function shortcutsSection() {
  const lines = [
    "## Keyboard shortcuts",
    "",
    "Each is written as on a Mac, then as on Windows and Linux.",
    "",
  ];
  for (const group of SHORTCUT_GUIDE_GROUPS) {
    if (group === "Developer") {
      continue;
    }
    lines.push(`### ${group}`, "");
    for (const entry of SHORTCUT_GUIDE_ENTRIES.filter(
      (shortcut) => shortcut.group === group,
    ).toSorted((a, b) => a.label.localeCompare(b.label))) {
      const mac = formatAcceleratorFor({
        accelerator: entry.accelerator,
        os: "mac",
      }).join("");
      // Windows and Linux write every chord here alike, which a test holds.
      const other = formatAcceleratorFor({
        accelerator: entry.accelerator,
        os: "windows",
      }).join("+");
      lines.push(
        `- ${entry.label}: ${mac} / ${other}${entry.noChordOnWindows ? " (not on Windows)" : ""}`,
      );
    }
    lines.push("");
  }
  return lines.join("\n");
}

function isDeveloperOnly(entry: SettingsEntry) {
  return entry.developerOnly === true;
}

/** A detail as a sentence, since some are written as a phrase. */
function sentence(text: string) {
  return /[.!?]$/.test(text) ? text : `${text}.`;
}
