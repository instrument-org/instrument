// Keeps docs/ true to the tree: every link and cited path resolves, every plan
// says what state it is in, and each section's index lists every file in it.
//
// `node scripts/docs.ts` checks; `--write` regenerates the indexes first, which
// `pnpm fix` does. Code renames are what break docs, so this runs wherever code
// lands, not only when a doc is edited.

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
process.chdir(root);

const PLAN_STATES = ["open", "done", "superseded", "dropped"] as const;
const INDEX_START = "<!-- index:start (generated by `pnpm fix`) -->";
const INDEX_END = "<!-- index:end -->";

const tracked = execFileSync(
  "git",
  ["ls-files", "--cached", "--others", "--exclude-standard"],
  {
    encoding: "utf8",
  },
)
  .split("\n")
  .filter((file) => file && existsSync(file));

const markdown = tracked.filter(
  (file) =>
    file.endsWith(".md") &&
    (file.startsWith("docs/") ||
      file.startsWith(".agents/") ||
      file === "AGENTS.md"),
);
const code = tracked.filter(
  (file) =>
    /\.(ts|tsx|mjs|cjs|js)$/.test(file) && !file.startsWith("registry/"),
);

const problems: string[] = [];

// Fenced blocks and inline code hold examples, not links.
function withoutCode(text: string): string {
  return text
    .replace(/^(```|~~~)[^\n]*\n[\s\S]*?^\1[^\n]*$/gm, "")
    .replace(/`[^`\n]*`/g, "");
}

function resolves(from: string, target: string): boolean {
  const [file] = target.split("#");
  if (!file) return true;
  if (/^[a-z][a-z+.-]*:/i.test(file)) return true;
  const resolved = file.startsWith("/")
    ? file.slice(1)
    : path.join(path.dirname(from), file);
  return existsSync(decodeURIComponent(resolved));
}

function checkLinks(): void {
  for (const file of markdown) {
    const text = withoutCode(readFileSync(file, "utf8"));
    for (const match of text.matchAll(/\]\(<?([^)\s>]+)>?(?:\s+"[^"]*")?\)/g)) {
      const [, target = ""] = match;
      if (!resolves(file, target))
        problems.push(`${file}: link to ${target} goes nowhere`);
    }
  }
  // Evergreen docs and indexes name repo paths in code spans too; history may
  // name a file since deleted, so only these are held to it.
  for (const file of markdown.filter(
    (f) => f.startsWith("docs/architecture/") || f.endsWith("README.md"),
  )) {
    const text = readFileSync(file, "utf8");
    for (const match of text.matchAll(
      /`((?:apps|packages|scripts|docs|\.agents|\.github)\/[^`\s*{}<>]+)`/g,
    )) {
      const [, path_ = ""] = match;
      const cited = path_.replace(/[.,:;)]+$/, "").replace(/:\d+(-\d+)?$/, "");
      if (!existsSync(cited))
        problems.push(`${file}: names ${cited}, which does not exist`);
    }
  }
  for (const file of code) {
    const text = readFileSync(file, "utf8");
    for (const match of text.matchAll(
      /\bdocs\/(?:architecture|decisions|findings|follow-ups|plans|reviews|changes)\/[\w./-]+\.md\b/g,
    )) {
      if (!existsSync(match[0]))
        problems.push(`${file}: cites ${match[0]}, which does not exist`);
    }
  }
}

type Doc = { file: string; name: string; title: string; text: string };

function docsIn(dir: string): Doc[] {
  return markdown
    .filter(
      (file) =>
        path.dirname(file) === dir && path.basename(file) !== "README.md",
    )
    .sort()
    .map((file) => {
      const text = readFileSync(file, "utf8");
      const title = (
        text.match(/^#\s+(.+)$/m)?.[1] ?? path.basename(file, ".md")
      )
        .replace(/^Plan:\s*/, "")
        .replace(/^\w/, (letter) => letter.toUpperCase());
      return { file, name: path.basename(file), title, text };
    });
}

function statusOf(text: string): string | undefined {
  return text.match(/^\**Status:?\**:?\s*(.+)$/im)?.[1];
}

// The status's opening, enough to choose what to open.
function summary(status: string): string {
  const plain = status
    .replace(/\*\*/g, "")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1");
  const sentence = plain.match(/^.+?[.;](?=\s|$)/)?.[0] ?? plain;
  return sentence.length > 160
    ? `${sentence.slice(0, 157).trimEnd()}...`
    : sentence;
}

function planIndex(): string {
  const plans = docsIn("docs/plans");
  const byState = new Map<string, string[]>(
    PLAN_STATES.map((state) => [state, []]),
  );
  for (const plan of plans) {
    const match = statusOf(plan.text)?.match(/^(\w+)\.\s*(.*)$/);
    const state = match?.[1];
    if (!state || !byState.has(state)) {
      problems.push(
        `${plan.file}: its first line under the title must be "Status: <${PLAN_STATES.join("|")}>. <where it stands>"`,
      );
      continue;
    }
    byState
      .get(state)
      ?.push(`- [${plan.title}](${plan.name}): ${summary(match[2] || state)}`);
  }
  return PLAN_STATES.filter((state) => byState.get(state)?.length)
    .map(
      (state) =>
        `### ${state.charAt(0).toUpperCase()}${state.slice(1)}\n\n${(byState.get(state) ?? []).join("\n")}`,
    )
    .join("\n\n");
}

function statusIndex(dir: string): string {
  return docsIn(dir)
    .map((doc) => {
      const status = statusOf(doc.text);
      return `- [${doc.title}](${doc.name})${status ? `: ${summary(status)}` : ""}`;
    })
    .join("\n");
}

function decisionIndex(): string {
  return docsIn("docs/decisions")
    .reverse()
    .map((doc) => {
      const head = doc.text.split("\n").slice(0, 12).join("\n");
      const note = head.match(
        /^>?\s*\**((?:Partly )?(?:Superseded|Retired|Narrowed)\b[^\n]*)$/im,
      )?.[1];
      return `- ${doc.name.slice(0, 10)} [${doc.title}](${doc.name})${note ? `: ${summary(note)}` : ""}`;
    })
    .join("\n");
}

const INDEXES: { readme: string; build: () => string }[] = [
  { readme: "docs/plans/README.md", build: planIndex },
  {
    readme: "docs/findings/README.md",
    build: () => statusIndex("docs/findings"),
  },
  {
    readme: "docs/follow-ups/README.md",
    build: () => statusIndex("docs/follow-ups"),
  },
  { readme: "docs/decisions/README.md", build: decisionIndex },
];

function checkIndexes(write: boolean): void {
  for (const { readme, build } of INDEXES) {
    const text = readFileSync(readme, "utf8");
    const start = text.indexOf(INDEX_START);
    const end = text.indexOf(INDEX_END);
    if (start < 0 || end < start) {
      problems.push(
        `${readme}: missing the ${INDEX_START} ... ${INDEX_END} markers`,
      );
      continue;
    }
    const next = `${text.slice(0, start)}${INDEX_START}\n\n${build()}\n\n${text.slice(end)}`;
    if (next === text) continue;
    if (write) writeFileSync(readme, next);
    else problems.push(`${readme}: index is out of date; run \`pnpm fix\``);
  }
  // Architecture's index is written by hand, for its descriptions.
  const architecture = readFileSync("docs/architecture/README.md", "utf8");
  for (const doc of docsIn("docs/architecture")) {
    if (!architecture.includes(`(${doc.name})`))
      problems.push(`docs/architecture/README.md: does not list ${doc.name}`);
  }
}

checkIndexes(process.argv.includes("--write"));
checkLinks();

if (problems.length > 0) {
  console.error(problems.join("\n"));
  console.error(`\n${problems.length} problem(s) in docs/.`);
  process.exit(1);
}
